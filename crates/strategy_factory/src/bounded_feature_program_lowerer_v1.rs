#[derive(Clone, Debug, Error, Eq, PartialEq)]
pub(crate) enum BoundedFeatureLoweringErrorV1 {
    #[error("joint-freeze Design bytes or identity are invalid")]
    Design,
    #[error("joint-freeze BFP bytes or identity are invalid")]
    Program,
    #[error("fixed first-party primitive catalog is unavailable or mismatched")]
    Catalog,
    #[error("first-party SDK source identity is mismatched")]
    SdkSource,
    #[error("primitive has no fixed first-party source lowering")]
    UnsupportedPrimitive,
    #[error("source identity input is invalid")]
    SourceIdentity,
    #[error("generated source exceeds its frozen bound")]
    SourceBounds,
}

impl From<BoundedFeatureProgramErrorV1> for BoundedFeatureLoweringErrorV1 {
    fn from(_: BoundedFeatureProgramErrorV1) -> Self {
        Self::Program
    }
}

