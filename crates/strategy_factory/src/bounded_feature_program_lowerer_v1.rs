/// Lowers only the exact R&D Owner-frozen Design/BFP pair into canonical executable ABI3 source.
pub(crate) fn prepare_frozen_bounded_feature_source_inputs_v1(
    frozen: &FrozenResearchBoundedFeatureProgramV1,
) -> Result<PrevalidatedBoundedFeatureSourceInputsV1, BoundedFeatureLoweringErrorV1> {
    // Reparse and re-canonicalize before source allocation. A stored digest is never trusted alone.
    let design: StrategyDesignV2 = serde_json::from_slice(frozen.design_bytes())
        .map_err(|_| BoundedFeatureLoweringErrorV1::Design)?;
    let canonical_design = prepare_canonical_strategy_design_v2(&design)
        .map_err(|_| BoundedFeatureLoweringErrorV1::Design)?;
    if canonical_design.canonical_bytes() != frozen.design_bytes()
        || canonical_design.design_identity() != frozen.design_identity()
        || canonical_design.design_digest() != frozen.design_digest()
        || design.research_request_identity != frozen.research_request_identity()
        || design.intent_identity != frozen.intent_identity()
        || design.intent_digest != frozen.intent_digest()
    {
        return Err(BoundedFeatureLoweringErrorV1::Design);
    }

    let catalog =
        PrimitiveCatalogV1::verify().map_err(|_| BoundedFeatureLoweringErrorV1::Catalog)?;
    let canonical_program =
        parse_bounded_feature_program_v1(frozen.program_bytes(), &design, catalog)?;
    let program = canonical_program.program();
    if canonical_program.digest() != frozen.program_digest()
        || program.catalog_digest.as_bytes() != &catalog.identity()
        || program.design_identity != frozen.design_identity()
        || program.design_digest != frozen.design_digest()
        || program.plugin_manifest_digest != frozen.plugin_manifest_digest()
        || program.research_request_identity != frozen.research_request_identity()
        || program.intent_identity != frozen.intent_identity()
        || program.intent_digest != frozen.intent_digest()
    {
        return Err(BoundedFeatureLoweringErrorV1::Program);
    }
    let manifest = design
        .plugins
        .iter()
        .find(|manifest| manifest.semantic_id == program.plugin_semantic_id)
        .ok_or(BoundedFeatureLoweringErrorV1::Design)?;
    let sdk_source_digest = first_party_bfp_sdk_source_digest_v1();
    if program.first_party_sdk_source_digest != sdk_source_digest {
        return Err(BoundedFeatureLoweringErrorV1::SdkSource);
    }

    // Exhaustive preflight. No generated source exists until every node has a known direct kernel call.
    let lowered_symbols = program
        .nodes
        .iter()
        .map(|node| {
            let row = catalog
                .row(&node.primitive_semantic_id)
                .ok_or(BoundedFeatureLoweringErrorV1::UnsupportedPrimitive)?;
            Ok::<_, BoundedFeatureLoweringErrorV1>(lowered_symbol(
                row.operation
                    .ok_or(BoundedFeatureLoweringErrorV1::UnsupportedPrimitive)?,
            ))
        })
        .collect::<Result<Vec<_>, _>>()?;

    let complete_kernel_source_digest = complete_kernel_source_digest()?;
    let guest_kernel_source_digest =
        source_list_digest(GUEST_KERNEL_SOURCE_DOMAIN, &GUEST_KERNEL_SOURCES)?;
    let lowerer_source_digest = domain_digest(
        LOWERER_SOURCE_DOMAIN,
        include_bytes!("bounded_feature_program_lowerer_v1.rs"),
    );
    let program_source = emit_program_source(
        &canonical_program,
        manifest,
        canonical_program.digest().as_bytes(),
        &lowered_symbols,
    )?;
    let mut files = vec![
        source_file(
            ".cargo/config.toml",
            frozen_config(manifest.max_linear_memory_bytes).as_bytes(),
        ),
        source_file("Cargo.lock", CARGO_LOCK),
        source_file("Cargo.toml", CARGO_TOML),
        source_file("src/lib.rs", LIB_SOURCE),
        source_file("src/program.rs", &program_source),
        source_file("src/sdk.rs", SDK_SOURCE),
    ];
    files.extend(
        GUEST_KERNEL_SOURCES
            .iter()
            .map(|(path, bytes)| source_file(path, bytes)),
    );
    files.sort_by(|left, right| left.path.as_bytes().cmp(right.path.as_bytes()));
    if !files.windows(2).all(|pair| pair[0].path < pair[1].path) {
        return Err(BoundedFeatureLoweringErrorV1::SourceIdentity);
    }
    let source_bytes = files.iter().try_fold(0_usize, |total, file| {
        total
            .checked_add(file.bytes.len())
            .ok_or(BoundedFeatureLoweringErrorV1::SourceBounds)
    })?;
    if source_bytes > program.bounds.max_source_bytes as usize {
        return Err(BoundedFeatureLoweringErrorV1::SourceBounds);
    }
    let source_set_digest = source_file_digest(&files)?;

    Ok(PrevalidatedBoundedFeatureSourceInputsV1 {
        _maturity: SourceMaturityV1::DeterministicExecutableSourceOnly,
        joint_freeze_digest: frozen.joint_freeze_digest(),
        program_digest: canonical_program.digest(),
        program_bytes: canonical_program.canonical_bytes().into(),
        plugin_semantic_id: program.plugin_semantic_id.clone().into_boxed_str(),
        manifest_digest: frozen.plugin_manifest_digest(),
        bounds: program.bounds.clone(),
        catalog_digest: program.catalog_digest,
        complete_kernel_source_digest,
        guest_kernel_source_digest,
        sdk_source_digest,
        lowerer_source_digest,
        source_set_digest,
        _files: files.into_boxed_slice(),
    })
}

