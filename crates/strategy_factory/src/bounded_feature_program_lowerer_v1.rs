fn lowered_symbol(operation: PrimitiveOperationV1) -> &'static str {
    match operation {
        PrimitiveOperationV1::Add => "FixedI128::checked_add_to_scale",
        PrimitiveOperationV1::Sub => "FixedI128::checked_sub_to_scale",
        PrimitiveOperationV1::Mul => "FixedI128::checked_mul",
        PrimitiveOperationV1::Div => "FixedI128::checked_div",
        PrimitiveOperationV1::Rescale => "FixedI128::rescale",
        PrimitiveOperationV1::Compare => "FixedI128::checked_compare",
        PrimitiveOperationV1::Select => "FixedI128::checked_select",
        PrimitiveOperationV1::Body => "FixedOhlc::body",
        PrimitiveOperationV1::Range => "FixedOhlc::range",
        PrimitiveOperationV1::UpperWick => "FixedOhlc::upper_wick",
        PrimitiveOperationV1::LowerWick => "FixedOhlc::lower_wick",
        PrimitiveOperationV1::Fraction => "fixed_range_fraction",
        PrimitiveOperationV1::Ema | PrimitiveOperationV1::Wilder => "FixedSmoothingState::advance",
        PrimitiveOperationV1::TrueRange | PrimitiveOperationV1::Atr | PrimitiveOperationV1::Gap => {
            "FixedBarState::advance"
        }
        PrimitiveOperationV1::Rsi => "FixedRsiState::advance",
        PrimitiveOperationV1::Lag
        | PrimitiveOperationV1::Sum
        | PrimitiveOperationV1::Mean
        | PrimitiveOperationV1::Minimum
        | PrimitiveOperationV1::Maximum
        | PrimitiveOperationV1::SwingHigh
        | PrimitiveOperationV1::SwingLow => "FixedWindowState::advance",
    }
}

fn emit_program_source(
    canonical: &CanonicalBoundedFeatureProgramV1,
    manifest: &PluginManifestV2,
    program_digest: &[u8; 32],
    lowered_symbols: &[&str],
) -> Result<Vec<u8>, BoundedFeatureLoweringErrorV1> {
    let program = canonical.program();
    let state_bytes = canonical.state_layout().total_bytes() as usize;
    let input_capacity = frame_capacity_v3(&manifest.input_ports, manifest.state.max_bytes, false)?;
    let output_capacity =
        frame_capacity_v3(&manifest.output_ports, manifest.state.max_bytes, true)?;
    let mut source = String::from(
        "#![allow(dead_code, unused_imports)]\n\nuse core::{convert::TryFrom as _, num::NonZeroU32, sync::atomic::{AtomicU8, Ordering}};\nuse crate::{ComparisonPredicateV1, DecimalScale, FixedBarState, FixedFeatureFailure, FixedI128, FixedRsiState, FixedSampleUpdate, FixedSmoothingKind, FixedSmoothingState, FixedStateFailure, FixedWindowFunction, FixedWindowState, ReducedUnitFraction, RoundingMode, SampleClockInputV1, fixed_range_fraction};\n\n",
    );
    push_byte_constant(&mut source, "PROGRAM_DIGEST", program_digest);
    for (ordinal, (node, symbol)) in program.nodes.iter().zip(lowered_symbols).enumerate() {
        let name = format!("NODE_{ordinal:04}_SEMANTIC_ID");
        push_byte_constant(&mut source, &name, node.primitive_semantic_id.as_bytes());
        let name = format!("NODE_{ordinal:04}_KERNEL_CALL");
        push_byte_constant(&mut source, &name, symbol.as_bytes());
    }
    writeln!(source, "const INPUT_CAPACITY: usize = {input_capacity};").unwrap();
    writeln!(source, "const OUTPUT_CAPACITY: usize = {output_capacity};").unwrap();
    writeln!(source, "const STATE_BYTES: usize = {state_bytes};").unwrap();
    source.push_str(EXECUTABLE_RUNTIME_SOURCE);

    let names = ValueNames::new(program)?;
    emit_input_decode(&mut source, program, manifest, &names)?;
    emit_constants(&mut source, program, &names)?;
    emit_state_initialization(&mut source, canonical, program, &names)?;
    emit_nodes(&mut source, program, &names)?;
    emit_state_bundle(&mut source, canonical, program, &names)?;
    emit_output_frame(&mut source, program, manifest, &names)?;
    source.push_str("}\n\n#[allow(unsafe_code)]\n#[unsafe(no_mangle)]\npub extern \"C\" fn strategy_factory_plugin_input_ptr_v2() -> i32 { INPUT.as_ptr().cast::<u8>() as usize as i32 }\n#[allow(unsafe_code)]\n#[unsafe(no_mangle)]\npub extern \"C\" fn strategy_factory_plugin_input_capacity_v2() -> i32 { INPUT_CAPACITY as i32 }\n#[allow(unsafe_code)]\n#[unsafe(no_mangle)]\npub extern \"C\" fn strategy_factory_plugin_output_ptr_v2() -> i32 { OUTPUT.as_ptr().cast::<u8>() as usize as i32 }\n#[allow(unsafe_code)]\n#[unsafe(no_mangle)]\npub extern \"C\" fn strategy_factory_plugin_output_capacity_v2() -> i32 { OUTPUT_CAPACITY as i32 }\n#[allow(unsafe_code)]\n#[unsafe(no_mangle)]\npub extern \"C\" fn strategy_factory_plugin_invoke_v2(input_len: i32) -> i32 {\n    if input_len < 0 { return -2; }\n    match run(input_len as usize) { Ok(len) => i32::try_from(len).unwrap_or(-2), Err(Failure::Numeric) => -1, Err(Failure::Unsupported) => -2 }\n}\n");
    Ok(source.into_bytes())
}

