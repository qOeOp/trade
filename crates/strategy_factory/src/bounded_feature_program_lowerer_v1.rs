fn push_bytes_literal(source: &mut String, bytes: &[u8]) {
    source.push_str("&[");
    for (index, byte) in bytes.iter().enumerate() {
        if index != 0 {
            source.push(',');
        }
        write!(source, "{byte}").unwrap();
    }
    source.push(']');
}

fn push_array_literal(source: &mut String, bytes: &[u8]) {
    source.push('[');
    for (index, byte) in bytes.iter().enumerate() {
        if index != 0 {
            source.push(',');
        }
        write!(source, "{byte}").unwrap();
    }
    source.push(']');
}

fn emit_input_decode(
    source: &mut String,
    program: &BoundedFeatureProgramProposalV1,
    manifest: &PluginManifestV2,
    names: &ValueNames,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    source.push_str("    let mut reader = Reader::new(input_len)?;\n    reader.header(");
    push_bytes_literal(source, program.plugin_manifest_digest.as_bytes());
    writeln!(source, ", {}u16)?;", manifest.input_ports.len() + 1).unwrap();
    for (ordinal, port) in manifest.input_ports.iter().enumerate() {
        let value_input = program
            .inputs
            .iter()
            .find(|input| input.value_port_semantic_id == port.semantic_id);
        let coordinate_input = program
            .inputs
            .iter()
            .find(|input| coordinate_port_id(input.input_role_identity) == port.semantic_id);
        match (
            value_input,
            coordinate_input,
            port.value_type,
            port.max_bytes,
        ) {
            (Some(input), None, ValueTypeV2::I128, 16) => {
                let name = names.name(&BoundedFeatureValueRefV1::InputValue {
                    input_role_id: input.input_role_id.clone(),
                })?;
                writeln!(
                    source,
                    "    let {name}_bytes = reader.entry::<16>({ordinal}u16, 4)?;"
                )
                .unwrap();
                writeln!(source, "    let {name} = Datum::fixed(numeric(FixedI128::new(i128::from_le_bytes({name}_bytes), {}u8))?);", input.scale).unwrap();
            }
            (None, Some(input), ValueTypeV2::Bytes, 308) => {
                let name = names.name(&BoundedFeatureValueRefV1::InputCoordinate {
                    input_role_id: input.input_role_id.clone(),
                })?;
                writeln!(
                    source,
                    "    let {name}_bytes = reader.entry::<308>({ordinal}u16, 5)?;"
                )
                .unwrap();
                writeln!(source, "    let {name} = Datum::raw(&{name}_bytes)?;").unwrap();
            }
            _ => return Err(BoundedFeatureLoweringErrorV1::Program),
        }
    }
    source.push_str("    let mut pre_state = [0u8; STATE_BYTES];\n    let pre_empty = reader.state(&mut pre_state)?;\n    reader.finish()?;\n");
    Ok(())
}

fn emit_constants(
    source: &mut String,
    program: &BoundedFeatureProgramProposalV1,
    names: &ValueNames,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    for constant in &program.constants {
        let name = names.name(&BoundedFeatureValueRefV1::Constant {
            constant_id: constant.constant_id.clone(),
        })?;
        source.push_str("    let ");
        source.push_str(name);
        source.push_str(" = ");
        match &constant.value {
            BoundedFeatureConstantValueV1::FixedI128 {
                coefficient, scale, ..
            } => {
                source.push_str("Datum::fixed(numeric(FixedI128::new(i128::from_le_bytes(");
                push_array_literal(source, &coefficient.to_le_bytes());
                writeln!(source, "), {scale}u8))?)").unwrap();
            }
            BoundedFeatureConstantValueV1::Boolean { value } => {
                writeln!(source, "Datum::boolean({value})").unwrap();
            }
            BoundedFeatureConstantValueV1::I32 { value } => {
                source.push_str("Datum::raw(");
                push_bytes_literal(source, &value.to_le_bytes());
                source.push_str(")?\n");
            }
            BoundedFeatureConstantValueV1::I64 { value } => {
                source.push_str("Datum::raw(");
                push_bytes_literal(source, &value.to_le_bytes());
                source.push_str(")?\n");
            }
            BoundedFeatureConstantValueV1::U64 { value } => {
                source.push_str("Datum::raw(");
                push_bytes_literal(source, &value.to_le_bytes());
                source.push_str(")?\n");
            }
            BoundedFeatureConstantValueV1::PositionIntentV1 { semantic_id }
            | BoundedFeatureConstantValueV1::TargetVariantV1 { semantic_id }
            | BoundedFeatureConstantValueV1::ProtectionVariantV1 { semantic_id } => {
                source.push_str("Datum::raw(");
                push_bytes_literal(source, semantic_id.as_bytes());
                source.push_str(")?\n");
            }
        }
        source.push_str(";\n");
    }
    Ok(())
}

fn emit_state_initialization(
    source: &mut String,
    canonical: &CanonicalBoundedFeatureProgramV1,
    program: &BoundedFeatureProgramProposalV1,
    names: &ValueNames,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    for (index, state_cell) in program.state_cells.iter().enumerate() {
        let BoundedFeatureStateKindV1::Strategy { value_type, .. } = &state_cell.state_kind else {
            continue;
        };
        let slot = canonical
            .state_layout()
            .slots()
            .get(index)
            .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
        let initial = slot
            .initial_bytes()
            .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
        let name = names.name(&BoundedFeatureValueRefV1::PriorState {
            state_id: state_cell.state_id.clone(),
        })?;
        writeln!(source, "    let {name}_raw: &[u8] = if pre_empty {{").unwrap();
        source.push_str("        ");
        push_bytes_literal(source, initial);
        source.push_str("\n    } else {\n");
        writeln!(
            source,
            "        &pre_state[{}usize..{}usize]",
            slot.offset(),
            slot.offset() + slot.width()
        )
        .unwrap();
        source.push_str("    };\n");
        emit_raw_to_datum(source, name, value_type, &format!("{name}_raw"))?;
    }
    Ok(())
}

fn emit_raw_to_datum(
    source: &mut String,
    name: &str,
    value_type: &BoundedFeatureValueTypeV1,
    raw: &str,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    match value_type {
        BoundedFeatureValueTypeV1::FixedI128 { scale, .. } => {
            writeln!(source, "    if {raw}.len() != 16 {{ return Err(Failure::Unsupported); }}").unwrap();
            writeln!(source, "    let mut {name}_coefficient = [0u8; 16]; {name}_coefficient.copy_from_slice({raw});").unwrap();
            writeln!(source, "    let {name} = Datum::fixed(numeric(FixedI128::new(i128::from_le_bytes({name}_coefficient), {scale}u8))?);").unwrap();
        }
        BoundedFeatureValueTypeV1::Boolean => {
            writeln!(source, "    if {raw}.len() != 1 {{ return Err(Failure::Unsupported); }}").unwrap();
            writeln!(source, "    let {name} = match {raw}[0] {{ 0 => Datum::boolean(false), 1 => Datum::boolean(true), _ => return Err(Failure::Unsupported) }};").unwrap();
        }
        BoundedFeatureValueTypeV1::I32 => writeln!(source, "    if {raw}.len() != 4 {{ return Err(Failure::Unsupported); }} let {name} = Datum::raw({raw})?;").unwrap(),
        BoundedFeatureValueTypeV1::I64 | BoundedFeatureValueTypeV1::U64 => writeln!(source, "    if {raw}.len() != 8 {{ return Err(Failure::Unsupported); }} let {name} = Datum::raw({raw})?;").unwrap(),
        BoundedFeatureValueTypeV1::OwnerSampleCoordinate { .. } => writeln!(source, "    if {raw}.len() != 308 {{ return Err(Failure::Unsupported); }} let {name} = Datum::raw({raw})?;").unwrap(),
        _ => return Err(BoundedFeatureLoweringErrorV1::Program),
    }
    Ok(())
}

fn emit_nodes(
    source: &mut String,
    program: &BoundedFeatureProgramProposalV1,
    names: &ValueNames,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    let catalog =
        PrimitiveCatalogV1::verify().map_err(|_| BoundedFeatureLoweringErrorV1::Catalog)?;
    for (node_index, node) in program.nodes.iter().enumerate() {
        let operation = catalog
            .row(&node.primitive_semantic_id)
            .and_then(|row| row.operation)
            .ok_or(BoundedFeatureLoweringErrorV1::UnsupportedPrimitive)?;
        let binding = |port: &str| -> Result<String, BoundedFeatureLoweringErrorV1> {
            let value = node
                .input_bindings
                .iter()
                .find(|value| value.port_id == port)
                .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
            names.name(&value.source).map(str::to_owned)
        };
        let outputs = node
            .output_ports
            .iter()
            .map(|port| {
                names.name(&BoundedFeatureValueRefV1::NodeOutput {
                    node_id: node.node_id.clone(),
                    port_id: port.port_id.clone(),
                })
            })
            .collect::<Result<Vec<_>, _>>()?;
        let ready = node
            .input_bindings
            .iter()
            .map(|value| {
                names
                    .name(&value.source)
                    .map(|name| format!("{name}.ready"))
            })
            .collect::<Result<Vec<_>, _>>()?
            .join(" && ");
        let ready = if ready.is_empty() {
            "true".to_owned()
        } else {
            ready
        };
        if is_stateful(operation) {
            emit_stateful_node(
                source, program, names, node_index, node, operation, &binding, &outputs, &ready,
            )?;
        } else {
            let output = outputs
                .first()
                .copied()
                .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
            writeln!(source, "    let {output} = if {ready} {{").unwrap();
            emit_stateless_expression(source, node, operation, &binding)?;
            source.push_str("    } else { Datum::warming() };\n");
        }
    }
    Ok(())
}

fn is_stateful(operation: PrimitiveOperationV1) -> bool {
    matches!(
        operation,
        PrimitiveOperationV1::Ema
            | PrimitiveOperationV1::Wilder
            | PrimitiveOperationV1::TrueRange
            | PrimitiveOperationV1::Atr
            | PrimitiveOperationV1::Gap
            | PrimitiveOperationV1::Rsi
            | PrimitiveOperationV1::Lag
            | PrimitiveOperationV1::Sum
            | PrimitiveOperationV1::Mean
            | PrimitiveOperationV1::Minimum
            | PrimitiveOperationV1::Maximum
            | PrimitiveOperationV1::SwingHigh
            | PrimitiveOperationV1::SwingLow
    )
}

