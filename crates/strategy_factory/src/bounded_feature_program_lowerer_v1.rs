#[derive(Clone, Copy)]
enum Failure { Numeric, Unsupported }

fn numeric<T>(value: Result<T, crate::NumericFailure>) -> Result<T, Failure> {
    value.map_err(|_| Failure::Numeric)
}
fn feature<T>(value: Result<T, FixedFeatureFailure>) -> Result<T, Failure> {
    value.map_err(|error| match error {
        FixedFeatureFailure::Numeric(_) | FixedFeatureFailure::InvalidOhlc => Failure::Numeric,
        _ => Failure::Unsupported,
    })
}
fn state<T>(value: Result<T, FixedStateFailure>) -> Result<T, Failure> {
    value.map_err(|error| match error {
        FixedStateFailure::Numeric(_) => Failure::Numeric,
        _ => Failure::Unsupported,
    })
}

#[derive(Clone, Copy)]
struct Datum { ready: bool, len: usize, bytes: [u8; 308] }
impl Datum {
    const fn warming() -> Self { Self { ready: false, len: 0, bytes: [0; 308] } }
    fn raw(bytes: &[u8]) -> Result<Self, Failure> {
        if bytes.len() > 308 { return Err(Failure::Unsupported); }
        let mut value = Self { ready: true, len: bytes.len(), bytes: [0; 308] };
        value.bytes[..bytes.len()].copy_from_slice(bytes);
        Ok(value)
    }
    fn fixed(value: FixedI128) -> Self {
        let mut result = Self { ready: true, len: 17, bytes: [0; 308] };
        result.bytes[..17].copy_from_slice(&value.to_canonical_bytes());
        result
    }
    fn boolean(value: bool) -> Self {
        let mut result = Self { ready: true, len: 1, bytes: [0; 308] };
        result.bytes[0] = u8::from(value);
        result
    }
    fn as_fixed(self) -> Result<FixedI128, Failure> {
        if !self.ready || self.len != 17 { return Err(Failure::Unsupported); }
        FixedI128::from_canonical_bytes(&self.bytes[..17]).map_err(|_| Failure::Unsupported)
    }
    fn as_bool(self) -> Result<bool, Failure> {
        if !self.ready || self.len != 1 { return Err(Failure::Unsupported); }
        match self.bytes[0] { 0 => Ok(false), 1 => Ok(true), _ => Err(Failure::Unsupported) }
    }
}

fn coordinate(value: &Datum) -> Result<SampleClockInputV1<'_>, Failure> {
    if !value.ready || value.len != 308 { return Err(Failure::Unsupported); }
    state(SampleClockInputV1::from_untrusted_bytes(&value.bytes))
}

struct Reader { cursor: usize, len: usize }
impl Reader {
    fn new(len: usize) -> Result<Self, Failure> {
        if len > INPUT_CAPACITY || len < 96 { return Err(Failure::Unsupported); }
        Ok(Self { cursor: 0, len })
    }
    fn byte_at(offset: usize) -> Result<u8, Failure> {
        INPUT.get(offset).map(|b| b.load(Ordering::Relaxed)).ok_or(Failure::Unsupported)
    }
    fn take<const N: usize>(&mut self) -> Result<[u8; N], Failure> {
        let end = self.cursor.checked_add(N).ok_or(Failure::Unsupported)?;
        if end > self.len { return Err(Failure::Unsupported); }
        let mut bytes = [0; N];
        let mut index = 0;
        while index < N { bytes[index] = Self::byte_at(self.cursor + index)?; index += 1; }
        self.cursor = end;
        Ok(bytes)
    }
    fn header(&mut self, manifest: &[u8; 32], value_count: u16) -> Result<(), Failure> {
        if self.take::<4>()? != *b"SFPI" || u16::from_le_bytes(self.take()?) != 2 || u16::from_le_bytes(self.take()?) != 3 { return Err(Failure::Unsupported); }
        if self.take::<32>()? != *manifest { return Err(Failure::Unsupported); }
        let _module = self.take::<32>()?;
        let _invocation = self.take::<16>()?;
        if u16::from_le_bytes(self.take()?) != value_count || u16::from_le_bytes(self.take()?) != 0 { return Err(Failure::Unsupported); }
        let body = usize::try_from(u32::from_le_bytes(self.take()?)).map_err(|_| Failure::Unsupported)?;
        if 96usize.checked_add(body) != Some(self.len) { return Err(Failure::Unsupported); }
        Ok(())
    }
    fn entry<const N: usize>(&mut self, ordinal: u16, tag: u8) -> Result<[u8; N], Failure> {
        if u16::from_le_bytes(self.take()?) != ordinal || self.take::<1>()?[0] != tag || self.take::<1>()?[0] != 0 || usize::try_from(u32::from_le_bytes(self.take()?)).ok() != Some(N) { return Err(Failure::Unsupported); }
        self.take()
    }
    fn state(&mut self, state_bytes: &mut [u8; STATE_BYTES]) -> Result<bool, Failure> {
        if u16::from_le_bytes(self.take()?) != 0xffff || self.take::<1>()?[0] != 5 || self.take::<1>()?[0] != 0 { return Err(Failure::Unsupported); }
        let len = usize::try_from(u32::from_le_bytes(self.take()?)).map_err(|_| Failure::Unsupported)?;
        if len == 0 { return Ok(true); }
        if len != STATE_BYTES { return Err(Failure::Unsupported); }
        let end = self.cursor.checked_add(len).ok_or(Failure::Unsupported)?;
        if end > self.len { return Err(Failure::Unsupported); }
        let mut index = 0;
        while index < len { state_bytes[index] = Self::byte_at(self.cursor + index)?; index += 1; }
        self.cursor = end;
        Ok(false)
    }
    fn finish(self) -> Result<(), Failure> { if self.cursor == self.len { Ok(()) } else { Err(Failure::Unsupported) } }
}

struct Writer { cursor: usize }
impl Writer {
    fn new() -> Self { Self { cursor: 0 } }
    fn byte(&mut self, value: u8) -> Result<(), Failure> {
        OUTPUT.get(self.cursor).ok_or(Failure::Unsupported)?.store(value, Ordering::Relaxed);
        self.cursor += 1; Ok(())
    }
    fn bytes(&mut self, values: &[u8]) -> Result<(), Failure> { for value in values { self.byte(*value)?; } Ok(()) }
    fn entry(&mut self, ordinal: u16, tag: u8, values: &[u8]) -> Result<(), Failure> {
        self.bytes(&ordinal.to_le_bytes())?; self.byte(tag)?; self.byte(0)?;
        self.bytes(&u32::try_from(values.len()).map_err(|_| Failure::Unsupported)?.to_le_bytes())?;
        self.bytes(values)
    }
    fn header(&mut self, count: u16) -> Result<(), Failure> {
        self.bytes(b"SFPO")?; self.bytes(&2u16.to_le_bytes())?; self.bytes(&3u16.to_le_bytes())?;
        let mut offset = 8; while offset < 88 { self.byte(Reader::byte_at(offset)?)?; offset += 1; }
        self.bytes(&count.to_le_bytes())?; self.bytes(&0u16.to_le_bytes())?; self.bytes(&0u32.to_le_bytes())
    }
    fn finish(self) -> Result<usize, Failure> {
        let body = self.cursor.checked_sub(96).ok_or(Failure::Unsupported)?;
        let bytes = u32::try_from(body).map_err(|_| Failure::Unsupported)?.to_le_bytes();
        for (index, value) in bytes.iter().enumerate() { OUTPUT[92 + index].store(*value, Ordering::Relaxed); }
        Ok(self.cursor)
    }
}

