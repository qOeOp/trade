struct ValueNames {
    names: BTreeMap<String, String>,
    types: BTreeMap<String, BoundedFeatureValueTypeV1>,
}

impl ValueNames {
    fn new(
        program: &BoundedFeatureProgramProposalV1,
    ) -> Result<Self, BoundedFeatureLoweringErrorV1> {
        let mut value = Self {
            names: BTreeMap::new(),
            types: BTreeMap::new(),
        };
        for (index, input) in program.inputs.iter().enumerate() {
            value.insert(
                format!("i:{}", input.input_role_id),
                format!("input_{index}_value"),
                BoundedFeatureValueTypeV1::FixedI128 {
                    unit: input.unit.clone(),
                    scale: input.scale,
                },
            )?;
            value.insert(
                format!("q:{}", input.input_role_id),
                format!("input_{index}_coordinate"),
                BoundedFeatureValueTypeV1::OwnerSampleCoordinate {
                    input_role_identity: input.input_role_identity,
                },
            )?;
        }
        for (index, constant) in program.constants.iter().enumerate() {
            value.insert(
                format!("c:{}", constant.constant_id),
                format!("constant_{index}"),
                constant_type(&constant.value),
            )?;
        }
        for (index, state) in program.state_cells.iter().enumerate() {
            if let BoundedFeatureStateKindV1::Strategy { value_type, .. } = &state.state_kind {
                value.insert(
                    format!("s:{}", state.state_id),
                    format!("prior_state_{index}"),
                    value_type.clone(),
                )?;
            }
        }
        for (node_index, node) in program.nodes.iter().enumerate() {
            for (port_index, port) in node.output_ports.iter().enumerate() {
                value.insert(
                    format!("n:{}:{}", node.node_id, port.port_id),
                    format!("node_{node_index}_output_{port_index}"),
                    port.value_type.clone(),
                )?;
            }
        }
        Ok(value)
    }

    fn insert(
        &mut self,
        key: String,
        name: String,
        value_type: BoundedFeatureValueTypeV1,
    ) -> Result<(), BoundedFeatureLoweringErrorV1> {
        if self.names.insert(key.clone(), name).is_some()
            || self.types.insert(key, value_type).is_some()
        {
            return Err(BoundedFeatureLoweringErrorV1::Program);
        }
        Ok(())
    }

    fn name(
        &self,
        source: &BoundedFeatureValueRefV1,
    ) -> Result<&str, BoundedFeatureLoweringErrorV1> {
        self.names
            .get(&value_ref_key(source))
            .map(String::as_str)
            .ok_or(BoundedFeatureLoweringErrorV1::Program)
    }

    fn value_type(
        &self,
        source: &BoundedFeatureValueRefV1,
    ) -> Result<&BoundedFeatureValueTypeV1, BoundedFeatureLoweringErrorV1> {
        self.types
            .get(&value_ref_key(source))
            .ok_or(BoundedFeatureLoweringErrorV1::Program)
    }
}

fn value_ref_key(source: &BoundedFeatureValueRefV1) -> String {
    match source {
        BoundedFeatureValueRefV1::InputValue { input_role_id } => format!("i:{input_role_id}"),
        BoundedFeatureValueRefV1::InputCoordinate { input_role_id } => format!("q:{input_role_id}"),
        BoundedFeatureValueRefV1::Constant { constant_id } => format!("c:{constant_id}"),
        BoundedFeatureValueRefV1::PriorState { state_id } => format!("s:{state_id}"),
        BoundedFeatureValueRefV1::NodeOutput { node_id, port_id } => {
            format!("n:{node_id}:{port_id}")
        }
    }
}

fn constant_type(value: &BoundedFeatureConstantValueV1) -> BoundedFeatureValueTypeV1 {
    match value {
        BoundedFeatureConstantValueV1::FixedI128 { unit, scale, .. } => {
            BoundedFeatureValueTypeV1::FixedI128 {
                unit: unit.clone(),
                scale: *scale,
            }
        }
        BoundedFeatureConstantValueV1::Boolean { .. } => BoundedFeatureValueTypeV1::Boolean,
        BoundedFeatureConstantValueV1::I32 { .. } => BoundedFeatureValueTypeV1::I32,
        BoundedFeatureConstantValueV1::I64 { .. } => BoundedFeatureValueTypeV1::I64,
        BoundedFeatureConstantValueV1::U64 { .. } => BoundedFeatureValueTypeV1::U64,
        BoundedFeatureConstantValueV1::PositionIntentV1 { .. } => {
            BoundedFeatureValueTypeV1::PositionIntentV1
        }
        BoundedFeatureConstantValueV1::TargetVariantV1 { .. } => {
            BoundedFeatureValueTypeV1::TargetVariantV1
        }
        BoundedFeatureConstantValueV1::ProtectionVariantV1 { .. } => {
            BoundedFeatureValueTypeV1::ProtectionVariantV1
        }
    }
}

