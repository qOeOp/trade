fn emit_stateless_expression(
    source: &mut String,
    node: &crate::bounded_feature_program_v1::BoundedFeatureNodeV1,
    operation: PrimitiveOperationV1,
    binding: &impl Fn(&str) -> Result<String, BoundedFeatureLoweringErrorV1>,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    let fixed = |port: &str| binding(port).map(|name| format!("{name}.as_fixed()?"));
    let output = match (&node.parameters, operation) {
        (
            BoundedFeatureParametersV1::OutputScale {
                output_scale,
                rounding,
            },
            PrimitiveOperationV1::Add,
        ) => format!(
            "Datum::fixed(numeric({}.checked_add_to_scale({}, numeric(DecimalScale::new({output_scale}))?, Some({})))?)",
            fixed("a")?,
            fixed("b")?,
            rounding_expr(*rounding)
        ),
        (
            BoundedFeatureParametersV1::OutputScale {
                output_scale,
                rounding,
            },
            PrimitiveOperationV1::Sub,
        ) => format!(
            "Datum::fixed(numeric({}.checked_sub_to_scale({}, numeric(DecimalScale::new({output_scale}))?, Some({})))?)",
            fixed("a")?,
            fixed("b")?,
            rounding_expr(*rounding)
        ),
        (
            BoundedFeatureParametersV1::OutputScale {
                output_scale,
                rounding,
            },
            PrimitiveOperationV1::Mul,
        ) => format!(
            "Datum::fixed(numeric({}.checked_mul({}, numeric(DecimalScale::new({output_scale}))?, Some({})))?)",
            fixed("a")?,
            fixed("b")?,
            rounding_expr(*rounding)
        ),
        (
            BoundedFeatureParametersV1::OutputScale {
                output_scale,
                rounding,
            },
            PrimitiveOperationV1::Div,
        ) => format!(
            "Datum::fixed(numeric({}.checked_div({}, numeric(DecimalScale::new({output_scale}))?, Some({})))?)",
            fixed("a")?,
            fixed("b")?,
            rounding_expr(*rounding)
        ),
        (
            BoundedFeatureParametersV1::OutputScale {
                output_scale,
                rounding,
            },
            PrimitiveOperationV1::Rescale,
        ) => format!(
            "Datum::fixed(numeric({}.rescale(numeric(DecimalScale::new({output_scale}))?, Some({})))?)",
            fixed("value")?,
            rounding_expr(*rounding)
        ),
        (
            BoundedFeatureParametersV1::ComparisonPredicate { predicate },
            PrimitiveOperationV1::Compare,
        ) => format!(
            "Datum::boolean(numeric({}.checked_compare({}, {}))?)",
            fixed("a")?,
            fixed("b")?,
            predicate_expr(*predicate)
        ),
        (BoundedFeatureParametersV1::None, PrimitiveOperationV1::Select) => format!(
            "Datum::fixed(numeric(FixedI128::checked_select({}.as_bool()?, {}, {}))?)",
            binding("condition")?,
            fixed("when_true")?,
            fixed("when_false")?
        ),
        (
            BoundedFeatureParametersV1::None,
            PrimitiveOperationV1::Body
            | PrimitiveOperationV1::Range
            | PrimitiveOperationV1::UpperWick
            | PrimitiveOperationV1::LowerWick,
        ) => {
            let method = match operation {
                PrimitiveOperationV1::Body => "body",
                PrimitiveOperationV1::Range => "range",
                PrimitiveOperationV1::UpperWick => "upper_wick",
                _ => "lower_wick",
            };
            format!(
                "Datum::fixed(numeric(feature(crate::FixedOhlc::new({}, {}, {}, {}))?.{method}())?)",
                fixed("open")?,
                fixed("high")?,
                fixed("low")?,
                fixed("close")?
            )
        }
        (
            BoundedFeatureParametersV1::RangeFraction {
                numerator,
                denominator,
                output_scale,
                rounding,
            },
            PrimitiveOperationV1::Fraction,
        ) => format!(
            "Datum::fixed(feature(fixed_range_fraction({}, {}, ReducedUnitFraction::new({numerator}, {denominator}).ok_or(Failure::Unsupported)?, numeric(DecimalScale::new({output_scale}))?, Some({})))?)",
            fixed("low")?,
            fixed("high")?,
            rounding_expr(*rounding)
        ),
        _ => return Err(BoundedFeatureLoweringErrorV1::Program),
    };
    writeln!(source, "        {output}").unwrap();
    Ok(())
}

#[allow(clippy::too_many_arguments)] // Each argument is a distinct frozen BFP lowering input.
fn emit_stateful_node(
    source: &mut String,
    program: &BoundedFeatureProgramProposalV1,
    names: &ValueNames,
    node_index: usize,
    node: &crate::bounded_feature_program_v1::BoundedFeatureNodeV1,
    operation: PrimitiveOperationV1,
    binding: &impl Fn(&str) -> Result<String, BoundedFeatureLoweringErrorV1>,
    outputs: &[&str],
    ready: &str,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    let state_id = node
        .state_id
        .as_ref()
        .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
    let state_index = program
        .state_cells
        .iter()
        .position(|cell| &cell.state_id == state_id)
        .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
    let state_cell = &program.state_cells[state_index];
    let state_start: u32 = program.state_cells[..state_index]
        .iter()
        .map(|cell| cell.max_bytes)
        .sum();
    let state_end = state_start
        .checked_add(state_cell.max_bytes)
        .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
    let clock_role = match node
        .update_clock
        .as_ref()
        .ok_or(BoundedFeatureLoweringErrorV1::Program)?
    {
        BoundedFeatureClockV1::Trigger { input_role_id }
        | BoundedFeatureClockV1::Sample { input_role_id, .. } => input_role_id,
    };
    let coordinate_name = format!(
        "input_{}_coordinate",
        program
            .inputs
            .iter()
            .position(|input| &input.input_role_id == clock_role)
            .ok_or(BoundedFeatureLoweringErrorV1::Program)?
    );
    let input_scale = match program.nodes[node_index]
        .input_bindings
        .first()
        .and_then(|binding| names.value_type(&binding.source).ok())
    {
        Some(BoundedFeatureValueTypeV1::FixedI128 { scale, .. }) => *scale,
        _ => return Err(BoundedFeatureLoweringErrorV1::Program),
    };
    let output_scale = node
        .output_ports
        .iter()
        .find_map(|port| match port.value_type {
            BoundedFeatureValueTypeV1::FixedI128 { scale, .. } => Some(scale),
            _ => None,
        })
        .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
    let state_name = format!("node_{node_index}_state");
    let (constructor, restore, encode) =
        state_constructor(operation, &node.parameters, input_scale, output_scale)?;
    writeln!(source, "    let mut {state_name} = {constructor};").unwrap();
    writeln!(source, "    if !pre_empty {{ state({state_name}.{restore}(&pre_state[{state_start}usize..{state_end}usize]))?; }}").unwrap();
    if outputs.len() == 2 {
        writeln!(
            source,
            "    let ({}, {}) = if {ready} {{",
            outputs[0], outputs[1]
        )
        .unwrap();
    } else {
        writeln!(source, "    let {} = if {ready} {{", outputs[0]).unwrap();
    }
    emit_stateful_advance(
        source,
        operation,
        &state_name,
        &coordinate_name,
        binding,
        outputs.len(),
    )?;
    if outputs.len() == 2 {
        source.push_str("    } else { (Datum::warming(), Datum::warming()) };\n");
    } else {
        source.push_str("    } else { Datum::warming() };\n");
    }
    writeln!(source, "    // state encoder: {encode}").unwrap();
    Ok(())
}

fn state_constructor(
    operation: PrimitiveOperationV1,
    parameters: &BoundedFeatureParametersV1,
    input_scale: u8,
    output_scale: u8,
) -> Result<(String, &'static str, &'static str), BoundedFeatureLoweringErrorV1> {
    let input = format!("numeric(DecimalScale::new({input_scale}u8))?");
    let output = format!("numeric(DecimalScale::new({output_scale}u8))?");
    let result = match (operation, parameters) {
        (
            PrimitiveOperationV1::Ema | PrimitiveOperationV1::Wilder,
            BoundedFeatureParametersV1::Period { period, rounding },
        ) => {
            let kind = if operation == PrimitiveOperationV1::Ema {
                "FixedSmoothingKind::Ema"
            } else {
                "FixedSmoothingKind::Wilder"
            };
            (
                format!(
                    "FixedSmoothingState::new({kind}, NonZeroU32::new({period}u32).ok_or(Failure::Unsupported)?, {input}, {})",
                    optional_rounding_expr(*rounding)
                ),
                "restore_canonical_bytes",
                "to_canonical_bytes",
            )
        }
        (PrimitiveOperationV1::TrueRange, BoundedFeatureParametersV1::None) => (
            format!("FixedBarState::new_true_range({input})"),
            "restore_canonical_bytes",
            "to_canonical_bytes",
        ),
        (PrimitiveOperationV1::Gap, BoundedFeatureParametersV1::None) => (
            format!("FixedBarState::new_gap({input})"),
            "restore_canonical_bytes",
            "to_canonical_bytes",
        ),
        (PrimitiveOperationV1::Atr, BoundedFeatureParametersV1::Period { period, rounding }) => (
            format!(
                "FixedBarState::new_atr(NonZeroU32::new({period}u32).ok_or(Failure::Unsupported)?, {input}, {})",
                optional_rounding_expr(*rounding)
            ),
            "restore_canonical_bytes",
            "to_canonical_bytes",
        ),
        (
            PrimitiveOperationV1::Rsi,
            BoundedFeatureParametersV1::PeriodAndOutputScale {
                period, rounding, ..
            },
        ) => {
            let capacity = period
                .checked_add(1)
                .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
            (
                format!(
                    "state(FixedRsiState::<{capacity}>::new(NonZeroU32::new({period}u32).ok_or(Failure::Unsupported)?, {input}, {output}, Some({})))?",
                    rounding_expr(*rounding)
                ),
                "restore_canonical",
                "encode_canonical",
            )
        }
        (
            PrimitiveOperationV1::Lag,
            BoundedFeatureParametersV1::Lag {
                offset,
                declared_max_lag,
            },
        ) => {
            let capacity = offset
                .checked_add(1)
                .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
            (
                format!(
                    "state(FixedWindowState::<{capacity}>::new_lag(NonZeroU32::new({offset}u32).ok_or(Failure::Unsupported)?, NonZeroU32::new({declared_max_lag}u32).ok_or(Failure::Unsupported)?, {input}))?"
                ),
                "restore_canonical",
                "encode_canonical",
            )
        }
        (
            PrimitiveOperationV1::Sum | PrimitiveOperationV1::Mean,
            BoundedFeatureParametersV1::WindowAndOutputScale {
                window, rounding, ..
            },
        )
        | (
            PrimitiveOperationV1::Minimum
            | PrimitiveOperationV1::Maximum
            | PrimitiveOperationV1::SwingHigh
            | PrimitiveOperationV1::SwingLow,
            BoundedFeatureParametersV1::Window { window, rounding },
        ) => {
            let function = match operation {
                PrimitiveOperationV1::Sum => "FixedWindowFunction::Sum",
                PrimitiveOperationV1::Mean => "FixedWindowFunction::Mean",
                PrimitiveOperationV1::Minimum => "FixedWindowFunction::Minimum",
                PrimitiveOperationV1::Maximum => "FixedWindowFunction::Maximum",
                PrimitiveOperationV1::SwingHigh => "FixedWindowFunction::SwingHigh",
                _ => "FixedWindowFunction::SwingLow",
            };
            (
                format!(
                    "state(FixedWindowState::<{window}>::new({function}, NonZeroU32::new({window}u32).ok_or(Failure::Unsupported)?, {input}, {output}, {}))?",
                    optional_rounding_expr(*rounding)
                ),
                "restore_canonical",
                "encode_canonical",
            )
        }
        _ => return Err(BoundedFeatureLoweringErrorV1::Program),
    };
    Ok(result)
}

fn emit_stateful_advance(
    source: &mut String,
    operation: PrimitiveOperationV1,
    state_name: &str,
    coordinate_name: &str,
    binding: &impl Fn(&str) -> Result<String, BoundedFeatureLoweringErrorV1>,
    output_count: usize,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    let fixed = |port: &str| binding(port).map(|name| format!("{name}.as_fixed()?"));
    match operation {
        PrimitiveOperationV1::Ema | PrimitiveOperationV1::Wilder => {
            writeln!(source, "        let update = state({state_name}.advance({}, coordinate(&{coordinate_name})?))?;", fixed("value")?).unwrap();
            source.push_str("        Datum::fixed(match update { FixedSampleUpdate::Advanced(value) | FixedSampleUpdate::Reused(value) => value })\n");
        }
        PrimitiveOperationV1::TrueRange | PrimitiveOperationV1::Atr | PrimitiveOperationV1::Gap => {
            writeln!(
                source,
                "        let bar = feature(crate::FixedOhlc::new({}, {}, {}, {}))?;",
                fixed("open")?,
                fixed("high")?,
                fixed("low")?,
                fixed("close")?
            )
            .unwrap();
            writeln!(source, "        let update = state({state_name}.advance(bar, coordinate(&{coordinate_name})?))?;").unwrap();
            source.push_str("        match update.value { Some(value) => Datum::fixed(value), None => Datum::warming() }\n");
        }
        PrimitiveOperationV1::Rsi => {
            writeln!(source, "        let update = state({state_name}.advance({}, coordinate(&{coordinate_name})?))?;", fixed("value")?).unwrap();
            source.push_str("        match update.value { Some(value) => Datum::fixed(value), None => Datum::warming() }\n");
        }
        PrimitiveOperationV1::Lag
        | PrimitiveOperationV1::Sum
        | PrimitiveOperationV1::Mean
        | PrimitiveOperationV1::Minimum
        | PrimitiveOperationV1::Maximum
        | PrimitiveOperationV1::SwingHigh
        | PrimitiveOperationV1::SwingLow => {
            writeln!(source, "        let update = state({state_name}.advance({}, coordinate(&{coordinate_name})?))?;", fixed("value")?).unwrap();
            if output_count == 2 {
                source.push_str("        match (update.output.sample_coordinate_bytes(), update.output.value()) {\n            (Some(coordinate), Some(value)) => (Datum::raw(coordinate)?, Datum::fixed(value)),\n            (None, None) => (Datum::warming(), Datum::warming()),\n            _ => return Err(Failure::Unsupported),\n        }\n");
            } else {
                source.push_str("        match update.output.value() { Some(value) => Datum::fixed(value), None => Datum::warming() }\n");
            }
        }
        _ => return Err(BoundedFeatureLoweringErrorV1::Program),
    }
    Ok(())
}

fn emit_state_bundle(
    source: &mut String,
    canonical: &CanonicalBoundedFeatureProgramV1,
    program: &BoundedFeatureProgramProposalV1,
    names: &ValueNames,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    source.push_str("    let mut post_state = [0u8; STATE_BYTES];\n");
    let catalog =
        PrimitiveCatalogV1::verify().map_err(|_| BoundedFeatureLoweringErrorV1::Catalog)?;
    for (index, cell) in program.state_cells.iter().enumerate() {
        let slot = canonical
            .state_layout()
            .slots()
            .get(index)
            .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
        let start = slot.offset();
        let end = start + slot.width();
        match &cell.state_kind {
            BoundedFeatureStateKindV1::Primitive => {
                let node_index = program
                    .nodes
                    .iter()
                    .position(|node| node.node_id == cell.writer_node_id)
                    .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
                let operation = catalog
                    .row(&program.nodes[node_index].primitive_semantic_id)
                    .and_then(|row| row.operation)
                    .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
                let state_name = format!("node_{node_index}_state");
                match operation {
                    PrimitiveOperationV1::Ema
                    | PrimitiveOperationV1::Wilder
                    | PrimitiveOperationV1::TrueRange
                    | PrimitiveOperationV1::Atr
                    | PrimitiveOperationV1::Gap => {
                        writeln!(source, "    post_state[{start}usize..{end}usize].copy_from_slice(&{state_name}.to_canonical_bytes());").unwrap();
                    }
                    _ => {
                        writeln!(source, "    state({state_name}.encode_canonical(&mut post_state[{start}usize..{end}usize]))?;").unwrap();
                    }
                }
            }
            BoundedFeatureStateKindV1::Strategy {
                value_type,
                source_port_id,
            } => {
                let writer_index = program
                    .nodes
                    .iter()
                    .position(|node| node.node_id == cell.writer_node_id)
                    .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
                let produced = names.name(&BoundedFeatureValueRefV1::NodeOutput {
                    node_id: cell.writer_node_id.clone(),
                    port_id: source_port_id.clone(),
                })?;
                let prior = names.name(&BoundedFeatureValueRefV1::PriorState {
                    state_id: cell.state_id.clone(),
                })?;
                writeln!(source, "    let state_{index}_value = if {produced}.ready {{ {produced} }} else {{ {prior} }};").unwrap();
                emit_datum_to_state(
                    source,
                    &format!("state_{index}_value"),
                    value_type,
                    start,
                    end,
                )?;
                let _ = writer_index;
            }
        }
    }
    let outputs = program
        .nodes
        .iter()
        .flat_map(|node| node.output_ports.iter().map(move |port| (node, port)))
        .map(|(node, port)| {
            names
                .name(&BoundedFeatureValueRefV1::NodeOutput {
                    node_id: node.node_id.clone(),
                    port_id: port.port_id.clone(),
                })
                .map(str::to_owned)
        })
        .collect::<Result<Vec<_>, _>>()?;
    let warming = if outputs.is_empty() {
        "false".to_owned()
    } else {
        outputs
            .iter()
            .map(|name| format!("!{name}.ready"))
            .collect::<Vec<_>>()
            .join(" || ")
    };
    writeln!(source, "    let warming = {warming};").unwrap();
    Ok(())
}

fn emit_datum_to_state(
    source: &mut String,
    datum: &str,
    value_type: &BoundedFeatureValueTypeV1,
    start: u32,
    end: u32,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    match value_type {
        BoundedFeatureValueTypeV1::FixedI128 { .. } => {
            writeln!(source, "    let state_fixed = {datum}.as_fixed()?; post_state[{start}usize..{end}usize].copy_from_slice(&state_fixed.coefficient().to_le_bytes());").unwrap();
        }
        BoundedFeatureValueTypeV1::Boolean => writeln!(source, "    post_state[{start}usize] = u8::from({datum}.as_bool()?);").unwrap(),
        BoundedFeatureValueTypeV1::I32 => writeln!(source, "    if {datum}.len != 4 {{ return Err(Failure::Unsupported); }} post_state[{start}usize..{end}usize].copy_from_slice(&{datum}.bytes[..4]);").unwrap(),
        BoundedFeatureValueTypeV1::I64 | BoundedFeatureValueTypeV1::U64 => writeln!(source, "    if {datum}.len != 8 {{ return Err(Failure::Unsupported); }} post_state[{start}usize..{end}usize].copy_from_slice(&{datum}.bytes[..8]);").unwrap(),
        BoundedFeatureValueTypeV1::OwnerSampleCoordinate { .. } => writeln!(source, "    if {datum}.len != 308 {{ return Err(Failure::Unsupported); }} post_state[{start}usize..{end}usize].copy_from_slice(&{datum}.bytes);").unwrap(),
        _ => return Err(BoundedFeatureLoweringErrorV1::Program),
    }
    Ok(())
}

fn emit_output_frame(
    source: &mut String,
    program: &BoundedFeatureProgramProposalV1,
    manifest: &PluginManifestV2,
    names: &ValueNames,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    writeln!(source, "    let mut writer = Writer::new(); writer.header({}u16)?; writer.byte(u8::from(warming))?;", manifest.output_ports.len() + 1).unwrap();
    source.push_str("    if warming {\n");
    for (ordinal, port) in manifest.output_ports.iter().enumerate() {
        source.push_str("        writer.entry(");
        write!(source, "{ordinal}u16, {}u8, ", wire_tag(port.value_type)).unwrap();
        match port.value_type {
            ValueTypeV2::PositionIntentV1 => push_bytes_literal(
                source,
                program.warmup.position_intent_semantic_id.as_bytes(),
            ),
            ValueTypeV2::TargetVariantV1 => {
                push_bytes_literal(source, program.warmup.target_variant_semantic_id.as_bytes());
            }
            ValueTypeV2::ProtectionVariantV1 => push_bytes_literal(
                source,
                program.warmup.protection_variant_semantic_id.as_bytes(),
            ),
            ValueTypeV2::I32 => push_bytes_literal(source, &0i32.to_le_bytes()),
            ValueTypeV2::I64 => push_bytes_literal(source, &0i64.to_le_bytes()),
            ValueTypeV2::U64 => push_bytes_literal(source, &0u64.to_le_bytes()),
            _ => return Err(BoundedFeatureLoweringErrorV1::Program),
        }
        source.push_str(")?;\n");
    }
    source.push_str("    } else {\n");
    let mut first = true;
    for (index, branch) in program.proposal_decision_table.branches.iter().enumerate() {
        let predicate = names.name(&branch.predicate)?;
        if first {
            write!(
                source,
                "        let selected = if {predicate}.as_bool()? {{ {index}u16 }}"
            )
            .unwrap();
            first = false;
        } else {
            write!(source, " else if {predicate}.as_bool()? {{ {index}u16 }}").unwrap();
        }
    }
    if first {
        source.push_str("        let selected = 0u16;\n");
    } else {
        writeln!(
            source,
            " else {{ {}u16 }};",
            program.proposal_decision_table.branches.len()
        )
        .unwrap();
    }
    source.push_str("        match selected {\n");
    for (index, branch) in program.proposal_decision_table.branches.iter().enumerate() {
        writeln!(source, "            {index}u16 => {{").unwrap();
        emit_ready_frame(source, &branch.frame, manifest, names, 16)?;
        source.push_str("            }\n");
    }
    writeln!(
        source,
        "            {}u16 => {{",
        program.proposal_decision_table.branches.len()
    )
    .unwrap();
    emit_ready_frame(
        source,
        &program.proposal_decision_table.default_frame,
        manifest,
        names,
        16,
    )?;
    source.push_str(
        "            }\n            _ => return Err(Failure::Unsupported),\n        }\n    }\n",
    );
    source.push_str("    writer.entry(0xffffu16, 5u8, &post_state)?;\n    writer.finish()\n");
    Ok(())
}

fn emit_ready_frame(
    source: &mut String,
    frame: &BoundedFeatureProposalFrameV1,
    manifest: &PluginManifestV2,
    names: &ValueNames,
    indent: usize,
) -> Result<(), BoundedFeatureLoweringErrorV1> {
    let pad = " ".repeat(indent);
    for (ordinal, port) in manifest.output_ports.iter().enumerate() {
        let terminal = frame
            .terminal_outputs
            .iter()
            .find(|terminal| terminal.manifest_port_id == port.semantic_id)
            .ok_or(BoundedFeatureLoweringErrorV1::Program)?;
        let datum = names.name(&terminal.source)?;
        writeln!(
            source,
            "{pad}if !{datum}.ready {{ return Err(Failure::Unsupported); }}"
        )
        .unwrap();
        match &terminal.conversion {
            BoundedFeatureTerminalConversionV1::Exact => {
                let expected = match port.value_type { ValueTypeV2::I32 => 4, ValueTypeV2::I64 | ValueTypeV2::U64 => 8, ValueTypeV2::I128 => 16, _ => 0 };
                if port.value_type == ValueTypeV2::I128 {
                    writeln!(source, "{pad}let terminal_fixed = {datum}.as_fixed()?; writer.entry({ordinal}u16, 4u8, &terminal_fixed.coefficient().to_le_bytes())?;").unwrap();
                } else {
                    if expected > 0 { writeln!(source, "{pad}if {datum}.len != {expected}usize {{ return Err(Failure::Unsupported); }}").unwrap(); }
                    writeln!(source, "{pad}writer.entry({ordinal}u16, {}u8, &{datum}.bytes[..{datum}.len])?;", wire_tag(port.value_type)).unwrap();
                }
            }
            BoundedFeatureTerminalConversionV1::FixedCoefficientToI32 { .. } => writeln!(source, "{pad}let terminal_value = i32::try_from({datum}.as_fixed()?.coefficient()).map_err(|_| Failure::Numeric)?.to_le_bytes(); writer.entry({ordinal}u16, 1u8, &terminal_value)?;").unwrap(),
            BoundedFeatureTerminalConversionV1::FixedCoefficientToI64 { .. } => writeln!(source, "{pad}let terminal_value = i64::try_from({datum}.as_fixed()?.coefficient()).map_err(|_| Failure::Numeric)?.to_le_bytes(); writer.entry({ordinal}u16, 2u8, &terminal_value)?;").unwrap(),
            BoundedFeatureTerminalConversionV1::FixedCoefficientToU64 { .. } => writeln!(source, "{pad}let terminal_value = u64::try_from({datum}.as_fixed()?.coefficient()).map_err(|_| Failure::Numeric)?.to_le_bytes(); writer.entry({ordinal}u16, 3u8, &terminal_value)?;").unwrap(),
        }
    }
    Ok(())
}

fn push_byte_constant(destination: &mut String, name: &str, bytes: &[u8]) {
    destination.push_str("pub const ");
    destination.push_str(name);
    destination.push_str(": &[u8] = &[");
    for (index, byte) in bytes.iter().enumerate() {
        if index != 0 {
            destination.push(',');
        }
        destination.push_str(&byte.to_string());
    }
    destination.push_str("];\n");
}

fn complete_kernel_source_digest() -> Result<BindingDigest, BoundedFeatureLoweringErrorV1> {
    source_list_digest(COMPLETE_KERNEL_SOURCE_DOMAIN, &COMPLETE_KERNEL_SOURCES)
}

fn source_list_digest(
    domain: &[u8],
    sources: &[(&str, &[u8])],
) -> Result<BindingDigest, BoundedFeatureLoweringErrorV1> {
    if sources.is_empty()
        || !sources.windows(2).all(|pair| pair[0].0 < pair[1].0)
        || sources.iter().any(|(path, bytes)| {
            path.is_empty()
                || !path.is_ascii()
                || bytes.is_empty()
                || path.len() > u16::MAX as usize
        })
    {
        return Err(BoundedFeatureLoweringErrorV1::SourceIdentity);
    }
    let mut hasher = Sha256::new();
    hasher.update(domain);
    hasher.update(
        u32::try_from(sources.len())
            .map_err(|_| BoundedFeatureLoweringErrorV1::SourceIdentity)?
            .to_le_bytes(),
    );
    for (path, bytes) in sources {
        hasher.update(
            u16::try_from(path.len())
                .map_err(|_| BoundedFeatureLoweringErrorV1::SourceIdentity)?
                .to_le_bytes(),
        );
        hasher.update(path.as_bytes());
        hasher.update(
            u32::try_from(bytes.len())
                .map_err(|_| BoundedFeatureLoweringErrorV1::SourceIdentity)?
                .to_le_bytes(),
        );
        hasher.update(bytes);
    }
    Ok(BindingDigest::from_untrusted_bytes(
        hasher.finalize().into(),
    ))
}

fn source_file_digest(
    files: &[LoweredSourceFileV1],
) -> Result<BindingDigest, BoundedFeatureLoweringErrorV1> {
    let sources = files
        .iter()
        .map(|file| (file.path(), file.bytes()))
        .collect::<Vec<_>>();
    source_list_digest(SOURCE_SET_DOMAIN, &sources)
}

fn domain_digest(domain: &[u8], bytes: &[u8]) -> BindingDigest {
    let mut hasher = Sha256::new();
    hasher.update(domain);
    hasher.update(bytes);
    BindingDigest::from_untrusted_bytes(hasher.finalize().into())
}

