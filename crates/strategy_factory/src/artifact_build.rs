#[async_trait]
impl ArtifactBuildSandboxPort for UnixArtifactBuildSandboxV1 {
    async fn build(
        &self,
        request: SandboxBuildRequestV1,
    ) -> Result<SandboxBuildProductV1, ArtifactBuildError> {
        let request = serde_json::to_vec(&request).map_err(sandbox)?;
        if request.len() > MAX_WIRE_BYTES {
            return Err(ArtifactBuildError::Sandbox(
                "request exceeds bound".to_string(),
            ));
        }
        let mut stream = UnixStream::connect(Path::new(self.socket.as_ref()))
            .await
            .map_err(sandbox)?;
        stream
            .write_u32(u32::try_from(request.len()).map_err(sandbox)?)
            .await
            .map_err(sandbox)?;
        stream.write_all(&request).await.map_err(sandbox)?;
        stream.flush().await.map_err(sandbox)?;
        let length = usize::try_from(stream.read_u32().await.map_err(sandbox)?).map_err(sandbox)?;
        if length == 0 || length > MAX_WIRE_BYTES {
            return Err(ArtifactBuildError::Sandbox(
                "response exceeds bound".to_string(),
            ));
        }
        let mut bytes = vec![0; length];
        stream.read_exact(&mut bytes).await.map_err(sandbox)?;
        let response: SandboxWireResponseV1 = serde_json::from_slice(&bytes).map_err(sandbox)?;
        if response.protocol != SANDBOX_PROTOCOL_V1 || response.outcome != "SUCCESS" {
            return Err(ArtifactBuildError::Sandbox(
                response
                    .failure_code
                    .unwrap_or_else(|| "SANDBOX_REJECTED".to_string()),
            ));
        }
        Ok(SandboxBuildProductV1 {
            source_capsule: decode(response.source_capsule_base64, "source capsule")?,
            build_recipe: decode(response.build_recipe_base64, "build recipe")?,
            wasm_one: decode(response.wasm_one_base64, "first Wasm")?,
            wasm_two: decode(response.wasm_two_base64, "second Wasm")?,
        })
    }
}

