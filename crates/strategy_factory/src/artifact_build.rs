fn verify_sandbox_source_capsule(
    actual: &[u8],
    expected_source: &[u8],
) -> Result<(), ArtifactBuildError> {
    let expected = canonical_sandbox_source_capsule(expected_source)?;
    if actual == expected {
        Ok(())
    } else {
        Err(ArtifactBuildError::Sandbox(
            "source capsule does not match the admitted candidate".to_string(),
        ))
    }
}

fn sandbox_source_capsule(
    manifest: &[u8],
    lock: &[u8],
    source: &[u8],
) -> Result<Vec<u8>, ArtifactBuildError> {
    let mut bytes = Vec::new();
    {
        let mut archive = tar::Builder::new(&mut bytes);
        append_capsule_entry(&mut archive, "Cargo.lock", lock)?;
        append_capsule_entry(&mut archive, "Cargo.toml", manifest)?;
        append_capsule_entry(&mut archive, "src/lib.rs", source)?;
        archive.finish().map_err(sandbox)?;
    }
    Ok(bytes)
}

fn append_capsule_entry(
    archive: &mut tar::Builder<&mut Vec<u8>>,
    path: &str,
    bytes: &[u8],
) -> Result<(), ArtifactBuildError> {
    let mut header = tar::Header::new_gnu();
    header.set_size(u64::try_from(bytes.len()).map_err(sandbox)?);
    header.set_mode(0o644);
    header.set_uid(0);
    header.set_gid(0);
    header.set_mtime(1);
    header.set_cksum();
    archive
        .append_data(&mut header, path, bytes)
        .map_err(sandbox)
}

pub(crate) fn validate_candidate(
    candidate: &ArtifactBuildCandidateV1,
    intent: &FrozenResearchGoalIntent,
) -> Result<String, ArtifactBuildError> {
    if candidate.schema_version != 1
        || candidate.intent_identity != intent.intent_identity()
        || candidate.intent_semantic_digest != intent.semantic_digest()
        || !candidate
            .candidate_identity
            .starts_with("agent-program-candidate-v1-")
        || !(16..=160).contains(&candidate.candidate_identity.len())
        || !candidate
            .candidate_identity
            .bytes()
            .all(valid_identity_byte)
    {
        return Err(ArtifactBuildError::Candidate("identity binding"));
    }

    if candidate.candidate_identity.contains("pilot")
        || candidate.candidate_identity.contains("template")
        || candidate
            .structured_logic_summary
            .contains("ResearchIntentProposal")
    {
        return Err(ArtifactBuildError::Candidate(
            "fixed or proposal-only candidate",
        ));
    }
    bounded_text(
        &candidate.structured_logic_summary,
        16,
        MAX_SUMMARY_BYTES,
        "logic summary",
    )?;
    bounded_text(
        &candidate.agent_change_explanation,
        16,
        MAX_EXPLANATION_BYTES,
        "agent explanation",
    )?;

    if !(2..=512).contains(&candidate.logic.lookback_bars)
        || !(1..=5_000).contains(&candidate.logic.entry_threshold_bps)
        || candidate.logic.exit_threshold_bps > candidate.logic.entry_threshold_bps
    {
        return Err(ArtifactBuildError::Candidate("logic parameters"));
    }
    candidate_digest(candidate)
}

pub(crate) fn candidate_digest(
    candidate: &ArtifactBuildCandidateV1,
) -> Result<String, ArtifactBuildError> {
    serde_json::to_vec(candidate)
        .map(|bytes| format!("sha256:{:x}", Sha256::digest(bytes)))
        .map_err(|_| ArtifactBuildError::Candidate("serialization"))
}

pub(crate) fn render_program_source(
    candidate: &ArtifactBuildCandidateV1,
    candidate_digest: &str,
) -> String {
    let tag = Sha256::digest(candidate_digest.as_bytes());
    let tag = tag.iter().map(u8::to_string).collect::<Vec<_>>().join(",");
    let signal = match candidate.logic.signal {
        GeneratedSignalV1::Momentum => 1,
        GeneratedSignalV1::MeanReversion => 2,
        GeneratedSignalV1::Breakout => 3,
    };
    let direction = match candidate.logic.direction {
        GeneratedDirectionV1::LongOnly => 1,
        GeneratedDirectionV1::ShortOnly => 2,
        GeneratedDirectionV1::LongShort => 3,
    };
    format!(
        r#"#![no_std]
use core::panic::PanicInfo;
const SIGNAL: u32 = {signal};
const DIRECTION: u32 = {direction};
const LOOKBACK: u32 = {lookback};
const ENTRY_BPS: u32 = {entry};
const EXIT_BPS: u32 = {exit};
const SEMANTIC_TAG: [u8; 32] = [{tag}];
static mut FRAME: [u8; 8192] = [0; 8192];
static mut OUTPUT: [u8; 8192] = [0; 8192];
#[unsafe(no_mangle)] pub extern "C" fn strategy_factory_frame_ptr_v1() -> u32 {{ core::ptr::addr_of_mut!(FRAME).cast::<u8>() as u32 }}
#[unsafe(no_mangle)] pub extern "C" fn strategy_factory_frame_capacity_v1() -> u32 {{ 8192 }}
#[unsafe(no_mangle)] pub extern "C" fn strategy_factory_proposal_ptr_v1() -> u32 {{ core::ptr::addr_of_mut!(OUTPUT).cast::<u8>() as u32 }}
#[unsafe(no_mangle)] pub extern "C" fn strategy_factory_proposal_capacity_v1() -> u32 {{ 8192 }}
#[unsafe(no_mangle)] pub extern "C" fn strategy_factory_on_event_v1(frame_len: u32) -> i32 {{
    if frame_len > 8192 {{ return -1; }}
    let index = ((frame_len ^ SIGNAL ^ DIRECTION ^ LOOKBACK ^ ENTRY_BPS ^ EXIT_BPS) & 31) as usize;
    unsafe {{ core::ptr::write_volatile(core::ptr::addr_of_mut!(OUTPUT).cast::<u8>(), SEMANTIC_TAG[index]); }}
    0
}}
#[panic_handler] fn panic(_: &PanicInfo<'_>) -> ! {{ loop {{ core::hint::spin_loop(); }} }}
"#,
        lookback = candidate.logic.lookback_bars,
        entry = candidate.logic.entry_threshold_bps,
        exit = candidate.logic.exit_threshold_bps,
    )
}

