pub(crate) fn build_request_semantic_digest(
    request: &ArtifactBuildRequestV1,
) -> Result<String, ArtifactBuildError> {
    #[derive(Serialize)]
    struct Meaning<'a> {
        build_request_identity: &'a str,
        attempt_identity: &'a str,
        intent_identity: &'a str,
        context: &'a TrustedProductEdgeContextV1,
    }

    for value in [
        request.build_request_identity.as_str(),
        request.attempt_identity.as_str(),
        request.intent_identity.as_str(),
    ] {
        if !(16..=160).contains(&value.len()) || !value.bytes().all(valid_identity_byte) {
            return Err(ArtifactBuildError::Candidate("request identity"));
        }
    }
    let bytes = serde_json::to_vec(&Meaning {
        build_request_identity: &request.build_request_identity,
        attempt_identity: &request.attempt_identity,
        intent_identity: &request.intent_identity,
        context: &request.context,
    })
    .map_err(|e| ArtifactBuildError::Storage(e.to_string()))?;
    Ok(format!("sha256:{:x}", Sha256::digest(bytes)))
}

