pub(crate) fn decode_sandbox_request(
    bytes: &[u8],
) -> Result<SandboxBuildRequestV1, ArtifactBuildError> {
    if bytes.is_empty() || bytes.len() > MAX_WIRE_BYTES {
        return Err(ArtifactBuildError::Sandbox(
            "request exceeds bound".to_string(),
        ));
    }
    let request: SandboxBuildRequestV1 = serde_json::from_slice(bytes).map_err(sandbox)?;
    if request.protocol != SANDBOX_PROTOCOL_V1
        || request.source.is_empty()
        || request.source.len() > 128 * 1024
        || !valid_sha256(&request.candidate_digest)
    {
        return Err(ArtifactBuildError::Sandbox(
            "request is invalid".to_string(),
        ));
    }
    Ok(request)
}

