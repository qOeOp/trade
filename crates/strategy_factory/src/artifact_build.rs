fn bounded_text(
    value: &str,
    minimum: usize,
    maximum: usize,
    label: &'static str,
) -> Result<(), ArtifactBuildError> {
    let trimmed = value.trim();
    if trimmed == value && (minimum..=maximum).contains(&value.len()) {
        Ok(())
    } else {
        Err(ArtifactBuildError::Candidate(label))
    }
}

fn valid_identity_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b':' | b'.')
}

fn valid_sha256(value: &str) -> bool {
    value.strip_prefix("sha256:").is_some_and(|digest| {
        digest.len() == 64 && digest.bytes().all(|byte| byte.is_ascii_hexdigit())
    })
}

fn decode(value: Option<String>, label: &str) -> Result<Vec<u8>, ArtifactBuildError> {
    let value = value.ok_or_else(|| ArtifactBuildError::Sandbox(format!("missing {label}")))?;
    BASE64.decode(value).map_err(sandbox)
}

fn sandbox(error: impl Display) -> ArtifactBuildError {
    ArtifactBuildError::Sandbox(error.to_string())
}

