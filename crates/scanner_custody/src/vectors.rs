/// Decodes one of this module's hex vectors.
///
/// # Panics
///
/// Panics when a vector is not even-length hex, which would mean this file was edited by hand.
#[must_use]
pub fn bytes(hex: &str) -> Vec<u8> {
    assert!(
        hex.len().is_multiple_of(2),
        "a hex vector has an even length"
    );
    (0..hex.len())
        .step_by(2)
        .map(|at| {
            u8::from_str_radix(&hex[at..at + 2], 16).expect("a hex vector holds only hex digits")
        })
        .collect()
}
